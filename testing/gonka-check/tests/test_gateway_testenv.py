class Cli(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.env = {name: os.environ.get(name) for name in ("XDG_CONFIG_HOME", "XDG_DATA_HOME")}
        os.environ["XDG_CONFIG_HOME"] = os.path.join(self.tmp.name, "config")
        os.environ["XDG_DATA_HOME"] = os.path.join(self.tmp.name, "data")

    def tearDown(self):
        for name, value in self.env.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value

    def gcheck(self, *args):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = cli.main(list(args))
        self.out, self.err = out.getvalue(), err.getvalue()
        return code

    @contextlib.contextmanager
    def docker_free(self, fake, last=lambda i, low, high: [low]):
        self.generated, self.downs, self.rotations = [], [], []

        def generate(stack, source, cache, devshardd, commit, version, log_path, octet=77, gateway_cpus=None,
                     host_cpus=None, rotation="off"):
            self.generated.append((stack.groups, stack.hosts, octet, gateway_cpus, host_cpus))
            self.rotations.append(rotation)
            stack.services = ["devshardctl", "versiond-0", "versiond-router"]
            stack.addresses = ["gonka1aaa"]

        with mock.patch.object(stress.shutil, "which", return_value="/usr/bin/docker"), \
                mock.patch.object(stress, "prepare_source", return_value=("/src/gonka", COMMIT)) as source, \
                mock.patch.object(testenv, "build_images", return_value=("/cache/devshardd", [])), \
                mock.patch.object(testenv.Stack, "generate", generate), \
                mock.patch.object(testenv.Stack, "up", lambda stack: fake.base), \
                mock.patch.object(testenv.Stack, "down", lambda stack: self.downs.append(stack.project)), \
                mock.patch.object(testenv.Stack, "exited", lambda stack: []), \
                mock.patch.object(testenv.Stack, "logs", lambda stack, service, tail=2000: "line\n"), \
                mock.patch.object(testenv.Stack, "stats", lambda stack: {}), \
                mock.patch.object(testenv.Stack, "gateway_log", lambda stack, since, until: fake.gateway_log()), \
                mock.patch.object(testenv.Stack, "diffs", lambda stack, i, low, high: last(i, low, high)), \
                mock.patch.object(stand, "memory_guard", return_value=None), \
                mock.patch.object(stand, "docker_root", return_value=None):
            yield source

    def run_dir(self):
        return self.out.split("written  ")[1].split(":")[0]

