class Timeline(unittest.TestCase):
    def sampler(self, events, samples=None, nonce=19866):
        events = {name: {"t_s": t_s, "nonce": 19866, "host_last_min": 19860, "host_last_max": 19866, "line": line}
                  for name, (t_s, line) in events.items()}
        samples = samples or [dict(sample("drive", 95, 19800), escrows=1), dict(sample("quiet", 130, 19866), escrows=2)]
        return types.SimpleNamespace(stop_t=100.0, nonce=nonce, events=events, counts={"auto_failed": 2},
                                     samples=samples)

    def test_a_settlement_of_the_gateway_itself(self):
        sampler = self.sampler({"nonce_high": (112.0, "a"), "deactivated": (113.0, "b"), "settled": (160.0, "c")})
        item = testenv.timeline("settle", sampler, 10)
        self.assertEqual((12.0, 13.0), tuple(item["events"][name]["after_s"] for name in ("nonce_high", "deactivated")))
        self.assertEqual({"state": "settled", "after_s": 60.0, "nonce": 19866, "host_last_min": 19860,
                          "host_last_max": 19866, "detail": None}, item["result"])
        self.assertEqual(1, item["escrows_before_stop"])
        self.assertEqual({"auto_failed": 2}, item["counts"])

    def test_the_first_failure_is_the_result(self):
        sampler = self.sampler({"auto_failed": (150.0, "auto_settle_failed escrow=1 attempt=1/30 error=late"),
                                "settle_failed": (149.0, 'devshard_settle_failed escrow=1 stage=finalize '
                                                         'error="insufficient signatures: 0/43 weight"')})
        result = testenv.timeline("settle", sampler, 10)["result"]
        self.assertEqual(("failed", 49.0, "insufficient signatures: 0/43 weight"),
                         (result["state"], result["after_s"], result["detail"]))
        self.assertEqual("none", testenv.timeline("settle", self.sampler({}), 10)["result"]["state"])

    def test_a_manual_settlement_and_heartbeats_after_the_deactivation(self):
        samples = [sample("drive", 95, 19800), sample("quiet", 120, 19866, heartbeats=5, last=19866),
                   dict(sample("quiet", 300, None, heartbeats=9, last=19990), escrows=2),
                   sample("quiet", 390, 20000, heartbeats=12, last=20000),
                   sample("settle", 400, 20000, heartbeats=12, last=20000), sample("final", 430, 20000)]
        sampler = self.sampler({"deactivated": (113.0, "devshard 1 deactivated: high_nonce")}, samples)
        manual = {"code": 502, "seconds": 30.0, "error": "insufficient signatures: 0/43 weight", "tx_hash": None}
        item = testenv.timeline("deactivate", sampler, 5, manual, 401.0)
        self.assertEqual({"state": "failed", "after_s": 301.0, "nonce": 20000, "host_last_min": 20000,
                          "host_last_max": 20000, "detail": "insufficient signatures: 0/43 weight"}, item["result"])
