class Verdict(unittest.TestCase):
    def verdict(self, item):
        result = testenv.judge(item)
        return result["verdict"], result["reason"]

    def test_a_settled_escrow_after_the_cap_passes(self):
        value, reason = self.verdict(summary())
        self.assertEqual("PASS", value)
        self.assertIn("weight 64 of 43", reason)

    def test_a_failed_finalize_after_the_cap_fails_with_the_evidence(self):
        final = {"code": 500, "seconds": 25.4, "weight": 0, "quorum": 43, "signatures": 0,
                 "error": "insufficient signatures: 0/43 weight"}
        value, reason = self.verdict(summary(final=final))
        self.assertEqual("FAIL", value)
        for part in ("finalize answered 500 insufficient signatures: 0/43 weight", "gateway nonce 20450",
                     "hosts' last diff 19869..19869", "active cap 19935", "40 refusals"):
            self.assertIn(part, reason)
        final["code"], final["weight"], final["error"] = 200, 40, None
        self.assertEqual("FAIL", self.verdict(summary(final=final))[0])

    def test_a_drive_that_never_reached_the_routing_stop_is_inconclusive(self):
        samples = [sample("drive", 0, 0), sample("drive", 600, 5200)]
        value, reason = self.verdict(summary(samples=samples, drive_reason="no nonce progress for 600 s"))
        self.assertEqual("INCONCLUSIVE", value)
        self.assertEqual("drive stopped at nonce 5200 of 19800: no nonce progress for 600 s", reason)

    def test_setup_errors_block_and_interrupts_are_inconclusive(self):
        self.assertEqual(("BLOCKED", "gencompose failed"),
                         self.verdict(testenv.summarize(64, 4, 8, "drive", None, None, [], None,
                                                        error="gencompose failed")))
        self.assertEqual("INCONCLUSIVE", self.verdict(summary(stop="interrupted"))[0])

    def test_a_stopped_gateway_fails_and_a_stopped_host_is_inconclusive(self):
        value, reason = self.verdict(summary(stopped=["gcheck-tenv-ab12-g64-devshardctl exited 137 (out of memory)"]))
        self.assertEqual("FAIL", value)
        self.assertIn("out of memory", reason)
        self.assertEqual("INCONCLUSIVE", self.verdict(summary(stopped=["gcheck-tenv-ab12-g64-versiond-2 exited 1"]))[0])

    def test_quiet_only_is_informational(self):
        samples = [sample("warm", 0, 30), sample("quiet", 10, 30, heartbeats=1),
                   sample("quiet", 130, 300, heartbeats=5), sample("final", 140, 365, heartbeats=5)]
        value, reason = self.verdict(summary(mode="quiet-only", samples=samples))
        self.assertEqual("PASS", value)
        self.assertIn("quiet 135.0 nonces/min, 67.5 per turn over 4 turns (G+1 = 65), 0 abandoned", reason)
        self.assertEqual("INCONCLUSIVE", self.verdict(summary(mode="quiet-only", samples=samples[:2]))[0])

    def test_dry_run_needs_chats_finalize_and_host_diffs(self):
        samples = [sample("warm", 0, 4), sample("final", 9, 13, last=4)]
        final = {"code": 200, "seconds": 5.9, "weight": 8, "quorum": 6}
        self.assertEqual("PASS", self.verdict(summary(mode="dry-run", samples=samples, final=final))[0])
        value, reason = self.verdict(summary(mode="dry-run", samples=samples[:1], final=final))
        self.assertEqual(("FAIL", "no host diffs readable through the router"), (value, reason))


