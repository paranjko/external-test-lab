class Fake(FakeGateway):
    """devshardctl of a testenv stack: heartbeat metrics, unquarantine, finalize with slot signatures, admin settle.

    With log set, the gateway log gives those lines once a chat met the routing stop; with pooled, /v1/status then
    lists escrow 1 as an inactive runtime next to its replacement and every read moves its nonce by idle_step."""

    def __init__(self, cap=None, groups=8, quorum_reached=True, quarantined=0, log="", pooled=False, idle_step=0,
                 settle_code=200, **kw):
        super().__init__(cap=cap, **kw)
        self.groups, self.quorum_reached, self.quarantined = groups, quorum_reached, quarantined
        self.unquarantined, self.heartbeats, self.paths = [], 0, []
        self.log, self.pooled, self.idle_step, self.settle_code = log, pooled, idle_step, settle_code
        self.routed, self.rotated = False, False

    def gateway_log(self):
        with self.lock:
            if not self.routed:
                return ""
            text, self.log, self.rotated = self.log, "", True
            return text

    def reply(self, method, path):
        with self.lock:
            self.paths.append((method, path))
            if method == "POST" and path == "/v1/chat/completions" and self.cap is not None and self.nonce >= self.cap:
                self.routed = True
            if method == "GET" and path == "/v1/status" and self.pooled and self.rotated:
                self.nonce += self.idle_step
                return 200, {"mode": "gateway", "runtimes": 2, "devshards": [
                    {"id": "1", "active": False, "nonce": self.nonce}, {"id": "2", "active": True}]}
            if method == "POST" and path == "/v1/admin/devshards/1/settle" and self.settle_code != 200:
                return self.settle_code, {"error": {"message": "insufficient signatures: 0/%d weight" %
                                                    stand.quorum(self.groups)}}
            if method == "POST" and path == "/v1/admin/devshards/1/settle":
                return 200, {"id": "1", "escrow_id": 1, "active": False, "tx_hash": "AB12", "settler": "gonka1ccc"}
            if method == "GET" and path == "/metrics":
                self.heartbeats += 1
                return 200, ("process_cpu_seconds_total %.2f\nprocess_resident_memory_bytes %d\n"
                             'devshard_gateway_heightsync_cadence_events_total{devshard_id="1",'
                             'event="heartbeat_opened"} %d\n' % (self.cpu, 90 * 2 ** 20, self.heartbeats))
            if method == "GET" and path == "/v1/status" and self.cap is None:
                self.nonce += self.groups + 1 if self.chats else 0
                return 200, {"nonce": self.nonce, "phase": "active"}
            if method == "POST" and path == "/v1/admin/participants/unquarantine":
                self.unquarantined.append(path)
                self.quarantined = 0
                return 200, {"cleared": True}
            if method == "POST" and path == "/v1/chat/completions" and self.quarantined:
                return 503, {"error": {"message": "no live host capacity"}}
            if method == "POST" and path == "/v1/finalize" and not self.quorum_reached:
                return 500, {"error": {"message": "insufficient signatures: 0/%d weight" % stand.quorum(self.groups)}}
            if method == "POST" and path == "/v1/finalize":
                signatures = [{"slot_id": i % self.groups, "signature": "x"} for i in range(self.groups + 2)]
                return 200, {"nonce": self.nonce + self.groups + 1, "signatures": signatures,
                             "host_stats": [{"slot_id": i} for i in range(self.groups)]}
        return super().reply(method, path)


def summary(mode="drive", final=None, samples=None, drive_reason=testenv.ROUTED_STOP, **extra):
    drive = None
    if mode == "drive":
        drive = testenv.Drive("http://127.0.0.1:1", 1, testenv.ROUTING_STOP, "t")
        drive.codes, drive.reason = {200: 16000}, drive_reason
    warm = testenv.Drive("http://127.0.0.1:1", 1, 0, "t")
    warm.codes = {200: 3 if mode == "dry-run" else 20}
    if samples is None:
        samples = [sample("warm", 0, 30), sample("drive", 5, 1000), sample("drive", 2005, 19800),
                   sample("quiet", 2010, 19800, heartbeats=0, last=19800),
                   sample("quiet", 2310, 20450, heartbeats=10, last=19869, cap=40),
                   sample("final", 2400, 20515, heartbeats=10, last=19869, cap=40)]
    if final is None:
        final = {"code": 200, "seconds": 2.5, "weight": 64, "quorum": 43, "signatures": 64, "nonce": 20515}
    return testenv.summarize(64, 4, 8, mode, warm, drive, samples, final, **extra)


def rotation(mode, events=None, result=None, heartbeats=None, escrows=1, counts=None):
    """A timeline as testenv.timeline leaves it: events in seconds after a routing stop at t_s 2005."""
    out = {"state": "none", "after_s": None, "nonce": None, "host_last_min": None, "host_last_max": None,
           "detail": None}
    out.update(result or {})
    return {"mode": mode, "window_min": 10, "stop_t": 2005.0, "events": {
        name: {"t_s": 2005.0 + after, "after_s": after, "nonce": 19800, "line": name}
        for name, after in (events or {}).items()}, "counts": counts or {}, "escrows_before_stop": escrows,
        "result": out, "heartbeats": heartbeats}


