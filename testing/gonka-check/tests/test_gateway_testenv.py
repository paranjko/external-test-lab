class Source(unittest.TestCase):
    def test_testenv_checkout_has_the_router_and_versiond_but_no_test_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            upstream = os.path.join(tmp, "upstream")
            for folder in ("devshard/user", "common", "inference-chain", "versioned", "versiond-router",
                           "router-runtime", "proxy"):
                os.makedirs(os.path.join(upstream, folder))
                with open(os.path.join(upstream, folder, "README"), "w", encoding="utf-8") as handle:
                    handle.write(folder + "\n")
            run = {"cwd": upstream, "check": True, "capture_output": True}
            subprocess.run(["git", "init", "--quiet"], **run)
            subprocess.run(["git", "add", "."], **run)
            subprocess.run(["git", "-c", "user.email=t@example.invalid", "-c", "user.name=t", "commit", "--quiet",
                            "-m", "init"], **run)
            subprocess.run(["git", "tag", stress.TAG], **run)
            commit = subprocess.run(["git", "rev-parse", "HEAD"], text=True, **run).stdout.strip()
            cache = os.path.join(tmp, "cache")
            path, _ = stress.prepare_source(cache, repo="file://" + upstream, pinned=commit)
            self.assertTrue(os.path.isfile(os.path.join(path, stress.TEST_FILE)))
            self.assertFalse(os.path.exists(os.path.join(path, "versioned")))
            path, _ = stress.prepare_source(cache, repo="file://" + upstream, pinned=commit, sparse=testenv.SPARSE,
                                            test_file=False)
            for folder in ("versioned", "versiond-router", "router-runtime", "devshard"):
                self.assertTrue(os.path.isdir(os.path.join(path, folder)), folder)
            self.assertFalse(os.path.exists(os.path.join(path, "proxy")))
            self.assertFalse(os.path.exists(os.path.join(path, stress.TEST_FILE)))


class Parsing(unittest.TestCase):
    def test_host_diff_replies(self):
        reply = json.dumps([{"diff": {"nonce": 560}, "state_hash": "x"}, {"diff": {"nonce": "569"}},
                            {"diff": {}}, "noise"])
        self.assertEqual([560, 569], testenv.diff_nonces(reply))
        self.assertEqual([], testenv.diff_nonces("[]"))
        self.assertIsNone(testenv.diff_nonces('{"message":"no storage configured"}'))
        self.assertIsNone(testenv.diff_nonces("curl: (7) Failed to connect"))

    def test_host_last_reads_from_what_the_host_had(self):
        stored = list(range(0, 19870))
        calls = []

        def fetch(low, high):
            calls.append((low, high))
            return [nonce for nonce in stored if low <= nonce <= high]

        self.assertEqual(19869, testenv.host_last(fetch, 19900))
        self.assertEqual([(19400, 20400)], calls)
        calls.clear()
        self.assertEqual(19869, testenv.host_last(fetch, 21000, known=19869))
        self.assertEqual([(19869, 21500)], calls)

    def test_host_last_walks_back_when_the_host_is_far_behind(self):
        stored = list(range(0, 535))
        calls = []

        def fetch(low, high):
            calls.append((low, high))
            return [nonce for nonce in stored if low <= nonce <= high]

        self.assertEqual(534, testenv.host_last(fetch, 3000))
        self.assertEqual([(2500, 3500), (1500, 2500), (500, 1500)], calls)
        self.assertIsNone(testenv.host_last(lambda low, high: [], 100))
        self.assertEqual(7, testenv.host_last(lambda low, high: None, 100, known=7))

