def compose_model():
    """A cut of `docker compose config --format json` of a gencompose file with two hosts."""
    def service(image, **extra):
        out = {"build": {"context": "/src", "dockerfile": "Dockerfile"}, "image": image, "environment": {},
               "networks": {"testenv": {"ipv4_address": "172.30.77.9"}}, "restart": "unless-stopped",
               "ports": [{"mode": "ingress", "host_ip": "127.0.0.1", "target": 1, "published": "1", "protocol": "tcp"}]}
        out.update(extra)
        return out

    hosts = {"versiond-%d" % i: service("devshard-versiond:latest", environment={"KEY_NAME": "versiond-%d" % i},
                                       networks={"testenv": {"ipv4_address": "172.30.77.1%d" % i,
                                                             "aliases": ["versiond-pool"]}},
                                       depends_on={"mock-chain": {"condition": "service_healthy"}})
             for i in range(2)}
    return {"name": "x", "networks": {"testenv": {"name": "x_testenv"}}, "services": dict(
        hosts, **{"devshard-postgres": {"image": "postgres:16-alpine"},
                  "mock-chain": service("devshard-mock-chain:latest"),
                  "mock-dapi": service("devshard-mock-dapi:latest", environment={"MOCK_DAPI_BINARY_DIR": "/b"}),
                  "mock-openai": service("devshard-mock-openai:latest"),
                  "versiond-router": service("devshard-versiond-router:latest", environment={
                      "GONKA_HA": "true", "VERSIOND_ROUTING_ACTIVATION_MIN_READY": "2",
                      "VERSIOND_ROUTING_CATALOG_POLL_SECONDS": "1"}, depends_on=["versiond-0", "devshard-postgres"]),
                  "devshardctl": service("devshard-runtime:latest", environment={
                      "DEVSHARD_PORT": "38081", "DEVSHARD_ADMIN_API_KEY": "testenv-citest-admin"},
                      depends_on={"devshard-postgres": {"condition": "service_started"}})})}


class Fake(FakeGateway):
    """devshardctl of a testenv stack: heartbeat metrics, unquarantine, finalize with slot signatures."""

    def __init__(self, cap=None, groups=8, quorum_reached=True, quarantined=0, **kw):
        super().__init__(cap=cap, **kw)
        self.groups, self.quorum_reached, self.quarantined = groups, quorum_reached, quarantined
        self.unquarantined, self.heartbeats = [], 0

    def reply(self, method, path):
        with self.lock:
            if method == "GET" and path == "/metrics":
                self.heartbeats += 1
                return 200, ("process_cpu_seconds_total %.2f\nprocess_resident_memory_bytes %d\n"
                             'devshard_gateway_heightsync_cadence_events_total{devshard_id="1",'
                             'event="heartbeat_opened"} %d\n' % (self.cpu, 90 * 2 ** 20, self.heartbeats))
            if method == "GET" and path == "/v1/status" and self.cap is None:
                self.nonce += self.groups + 1 if self.chats else 0
                return 200, {"nonce": self.nonce, "phase": "active"}
            if method == "POST" and path == "/v1/admin/participants/unquarantine":
                self.unquarantined.append(path)
                self.quarantined = 0
                return 200, {"cleared": True}
            if method == "POST" and path == "/v1/chat/completions" and self.quarantined:
                return 503, {"error": {"message": "no live host capacity"}}
            if method == "POST" and path == "/v1/finalize" and not self.quorum_reached:
                return 500, {"error": {"message": "insufficient signatures: 0/%d weight" % stand.quorum(self.groups)}}
            if method == "POST" and path == "/v1/finalize":
                signatures = [{"slot_id": i % self.groups, "signature": "x"} for i in range(self.groups + 2)]
                return 200, {"nonce": self.nonce + self.groups + 1, "signatures": signatures,
                             "host_stats": [{"slot_id": i} for i in range(self.groups)]}
        return super().reply(method, path)


def summary(mode="drive", final=None, samples=None, drive_reason=testenv.ROUTED_STOP, **extra):
    drive = None
    if mode == "drive":
        drive = testenv.Drive("http://127.0.0.1:1", 1, testenv.ROUTING_STOP, "t")
        drive.codes, drive.reason = {200: 16000}, drive_reason
    warm = testenv.Drive("http://127.0.0.1:1", 1, 0, "t")
    warm.codes = {200: 3 if mode == "dry-run" else 20}
